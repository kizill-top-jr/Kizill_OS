/* ---- low level ---- */

static inline void put_px(u64 x, u64 y, u32 color) {
    if (x >= g_fb->width || y >= g_fb->height) return;
    u32 *p = (u32 *)((u8 *)g_fb->address + y * g_fb->pitch + x * (g_fb->bpp / 8));
    *p = color;
}

void fb_put_pixel(u64 x, u64 y, u32 color) { put_px(x, y, color); }

void fb_clear(u32 color) {
    for (u64 y = 0; y < g_fb->height; y++)
        for (u64 x = 0; x < g_fb->width; x++)
            put_px(x, y, color);
    g_cursor_x = 0;
    g_cursor_y = 0;
}

void fb_init(struct limine_framebuffer *fb) {
    g_fb = fb;
    g_cursor_x = 0;
    g_cursor_y = 0;
}

/* ---- drawing ---- */

void fb_draw_char(u64 px, u64 py, char c, u32 fg, u32 bg) {
    if ((u8)c < 32 || (u8)c > 127) c = '?';
    const u8 *glyph = font[(u8)c - 32];

    for (u64 row = 0; row < FONT_H; row++) {
        u8 bits = glyph[row];
        for (u64 col = 0; col < FONT_W; col++) {
            u32 color = (bits & (0x80 >> col)) ? fg : bg;
            put_px(px + col, py + row, color);
        }
    }
}

void fb_draw_string(u64 px, u64 py, const char *s, u32 fg, u32 bg) {
    u64 x = px;
    for (; *s; s++) {
        fb_draw_char(x, py, *s, fg, bg);
        x += FONT_W;
    }
}

/* ---- console ---- */

static void scroll_up(void) {
    u64 line_bytes = g_fb->pitch * FONT_H;
    u64 total = g_fb->pitch * g_fb->height;
    u8 *dst = (u8 *)g_fb->address;
    u8 *src = dst + line_bytes;
    u64 n = total - line_bytes;
    for (u64 i = 0; i < n; i++) dst[i] = src[i];

    /* clear bottom line */
    for (u64 y = g_fb->height - FONT_H; y < g_fb->height; y++)
        for (u64 x = 0; x < g_fb->width; x++)
            put_px(x, y, g_bg);
}

static void put_char(char c) {
    if (c == '\n') {
        g_cursor_x = 0;
        g_cursor_y++;
    } else if (c == '\r') {
        g_cursor_x = 0;
    } else if (c == '\t') {
        g_cursor_x = (g_cursor_x + 4) & ~3;
    } else {
        fb_draw_char(g_cursor_x * FONT_W, g_cursor_y * FONT_H, c, g_fg, g_bg);
        g_cursor_x++;
    }

    u64 cols = g_fb->width / FONT_W;
    u64 rows = g_fb->height / FONT_H;

    if (g_cursor_x >= cols) {
        g_cursor_x = 0;
        g_cursor_y++;
    }
    if (g_cursor_y >= rows) {
        scroll_up();
        g_cursor_y = rows - 1;
    }
}

void printk_color(const char *s, u32 fg) {
    u32 old = g_fg;
    g_fg = fg;
    while (*s) put_char(*s++);
    g_fg = old;
}

void printk(const char *s) {
    while (*s) put_char(*s++);
}

void printk_hex(u64 v) {
    const char *h = "0123456789ABCDEF";
    printk("0x");
    for (int i = 60; i >= 0; i -= 4)
        put_char(h[(v >> i) & 0xF]);
}

void printk_dec(u64 v) {
    if (v == 0) { put_char('0'); return; }
    char buf[24];
    int i = 0;
    while (v) { buf[i++] = '0' + (v % 10); v /= 10; }
    while (i--) put_char(buf[i]);
}
